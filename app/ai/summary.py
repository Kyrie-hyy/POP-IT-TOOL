from app.ai.client import ai_client


class AISummary:

    def summarize(self, user_input, results):

        prompt = f"""
你是一名拥有多年经验的企业 IT 运维工程师。

下面是用户的问题以及工具检测结果，请生成一份专业的 AI 智能诊断报告。

========================
用户问题
========================

{user_input}

========================
工具执行结果
========================

{results}

========================
请完成以下内容
========================

请按照下面格式输出。

━━━━━━━━━━━━━━━━━━
🤖 AI 智能诊断报告

【问题】
一句话描述用户的问题。

【检测结果】
根据执行结果，总结检测到的信息。

【AI 判断】
分析最可能的原因。

【建议】
给出 3~5 条处理建议。
如果检测正常，也要告诉用户下一步应该检查什么。

【是否建议重启】
回答：
建议重启
或者
无需重启

【诊断可信度】
例如：
92%

━━━━━━━━━━━━━━━━━━

要求：

1. 全部使用中文。

2. 不要 Markdown。

3. 不要 JSON。

4. 不超过300字。

5. 风格专业、像企业 IT 运维助手。

6. 如果工具执行成功，不要说"未知错误"。

7. 如果网络检测正常，不要建议重装系统。

8. 如果没有明显异常，要说明网络正常，并分析更可能的原因。

"""

        return ai_client.chat_text(prompt)


ai_summary = AISummary()